    /// TLD 物品重量换算与默认重量表。
    /// 存档中 m_WeightKG 的存储格式为 实际kg × 1e9(即 1kg = 1000000000)。
    /// 游戏读取存档时会除以 1e9 还原为真实 kg,因此工具必须做同样换算。
